import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const root = path.resolve(import.meta.dirname,'..');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('index.html');
const css=read('assets/css/app.css');
const js=read('assets/js/app.js');
assert.match(html, /assets\/css\/app\.css/);
assert.match(html, /assets\/js\/app\.js/);
assert.match(html, /<div id="view"/);
assert.ok(css.length>1000);
assert.ok(js.length>50000);
new vm.Script(js,{filename:'app.js'});
assert.match(js,/const MODULES=\[/);
assert.match(js,/render\(\)/);
assert.match(read('netlify.toml'),/publish = "\."/);
console.log('PASS: Source structure, HTML links, JavaScript syntax, and Netlify settings');
